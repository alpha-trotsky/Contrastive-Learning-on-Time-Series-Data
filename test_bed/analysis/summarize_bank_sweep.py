"""Summarise analysis/bank_sweep.py runs: one table per (domain, dial, encoder), rows =
model, columns = bank size; entries = energy above the oracle (%) and the mean largest
bank weight, averaged over seeds.

Usage (from test_bed/):  python -m analysis.summarize_bank_sweep
"""
import json
from collections import defaultdict
from pathlib import Path

DIR = Path('results/bank_sweep')
NAMES = {'cosine': 'dot (unnormalised)', 'cosine_tanh': 'dot, tanh future encoder',
         'ncos': 'normalised cosine', 'l2': 'L2 one-way', 'l2_joint': 'L2 joint'}


def main():
    runs = defaultdict(list)
    for f in sorted(DIR.glob('*.json')):
        d = json.load(open(f))
        a = d['args']
        runs[(a['domain'], a['dial'], a['encoder'], a['model'])].append(d)
    lines = ['# Bank-size sweep', '',
             'Generated by `python -m analysis.summarize_bank_sweep`. Each cell: energy above the '
             'oracle in % / mean largest bank weight, averaged over seeds (n). The model is '
             'trained once; only the bank of held-out futures changes.', '']
    for key in sorted({k[:3] for k in runs}, key=lambda k: (k[0], -k[1], k[2])):
        dom, dial, enc = key
        models = [m for m in NAMES if (dom, dial, enc, m) in runs]
        sizes = [r['bank'] for r in runs[(dom, dial, enc, models[0])][0]['rows']]
        lines += [f'## {dom}, dial {dial:g}, {enc} encoders', '',
                  '| model | n | ' + ' | '.join(f'{b:,}' for b in sizes) + ' |',
                  '|' + '---|' * (2 + len(sizes))]
        for m in models:
            ds = runs[(dom, dial, enc, m)]
            cells = []
            for i in range(len(sizes)):
                ex = sum(d['rows'][i]['excess_pct'] for d in ds) / len(ds)
                wm = sum(d['rows'][i]['wmax_mean'] for d in ds) / len(ds)
                cells.append(f'{ex:+.1f} / {wm:.2f}')
            lines.append(f'| {NAMES[m]} | {len(ds)} | ' + ' | '.join(cells) + ' |')
        lines.append('')
    (DIR / 'summary.md').write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
