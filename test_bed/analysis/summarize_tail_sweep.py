"""Tables for analysis/tail_sweep.py results (markdown + LaTeX rows).

Usage (from test_bed/):  python -m analysis.summarize_tail_sweep
Writes results/tail_sweep/summary.md and results/tail_sweep/tables.tex.
"""
import glob
import json
import math
import statistics as st
from collections import defaultdict
from pathlib import Path

OUT = Path('results/tail_sweep')
SIZES = [100, 1000, 10000, 30000, 100000, 200000]
# (score, loss, train) -> label, in table order
MODELS = [
    (('dot', 'twoway', 'kl'), 'inner product (unbounded)'),
    (('tanh', 'twoway', 'kl'), 'inner product, $\\tanh$ future'),
    (('ncos', 'twoway', 'kl'), 'normalized cosine'),
    (('l2', 'oneway', 'kl'), '$L^2$ one-way'),
    (('l2', 'joint', 'kl'), '$L^2$ joint'),
    (('tk', 'oneway', 'kl'), 'Student-$t$ kernel, one-way'),
    (('tk', 'joint', 'kl'), 'Student-$t$ kernel, joint'),
    (('tk2', 'oneway', 'kl'), 'log-quadratic, one-way'),
    (('tk2', 'joint', 'kl'), 'log-quadratic, joint'),
    (('dot', 'twoway', 'hyb10'), 'inner product + bank energy'),
    (('tanh', 'twoway', 'hyb10'), '$\\tanh$ future + bank energy'),
    (('ncos', 'twoway', 'hyb10'), 'normalized cosine + bank energy'),
    (('l2', 'oneway', 'hyb10'), '$L^2$ one-way + bank energy'),
    (('dot', 'twoway', 'es'), 'inner product, bank energy only'),
    (('tanh', 'twoway', 'es'), '$\\tanh$ future, bank energy only'),
]
LABEL = dict(MODELS)


def load():
    runs = defaultdict(list)                     # (data, encoder, key) -> [result]
    for f in sorted(glob.glob(str(OUT / '*.json'))):
        r = json.load(open(f))
        a = r['args']
        train = a['train'] + (f"{a['lam']:g}" if a['train'] == 'hyb' else '')
        data = a['data'] + (f"{a['dial']:g}" if a['data'] == 't' else '')
        runs[(data, a['encoder'], (a['score'], a['loss'], train))].append(r)
    return runs


def ms(xs):
    """mean and standard error over seeds."""
    m = st.mean(xs)
    return m, (st.stdev(xs) / math.sqrt(len(xs)) if len(xs) > 1 else float('nan'))


def row_at(r, B):
    for x in r['rows']:
        if x['bank'] == B:
            return x
    return None


def sizes_for(rs):
    have = sorted({x['bank'] for r in rs for x in r['rows']})
    return [B for B in SIZES if B in have] + [B for B in have if B > max(SIZES)]


def fmt_pm(m, se, digits=1):
    if math.isnan(se):
        return f'{m:+.{digits}f}'
    return f'{m:+.{digits}f} ± {se:.{digits}f}'


def of_factor(r, B, k, calm=False):
    """Over-forecast factor of the event {|v| > t_p}: its forecast probability,
    averaged over the test pasts, divided by its marginal probability p."""
    return row_at(r, B)['tail_weight_calm' if calm else 'tail_weight'][k] / r['tail_p'][k]


def of_oracle(r, k, calm=False):
    key = 'p_true_calm' if calm else 'p_true_mean'
    return r[key][k] / r['tail_p'][k] if r.get(key) else float('nan')


def main():
    runs = load()
    md, tex = ['# Tail sweep', '', 'Generated by `python -m analysis.summarize_tail_sweep`. '
               'Mean ± standard error over seeds (n).', ''], []
    groups = sorted({(d, e) for d, e, _ in runs})
    for data, enc in groups:
        any_rs = next(rs for (d, e, _), rs in runs.items() if (d, e) == (data, enc))
        sizes = sizes_for(any_rs)
        ref = any_rs[0]['ref']
        md += [f'## {data}, {enc} encoders', '', f'Energy score above the {ref} (%), by bank size.', '',
               '| model | n | ' + ' | '.join(f'{B:,}' for B in sizes) + ' | turn |', '|---|---|' + '---|' * (len(sizes) + 1)]
        tex += [f'%% ---- {data}, {enc}: energy excess (%) by bank size {sizes}']
        diag = []
        for key, label in MODELS:
            rs = runs.get((data, enc, key))
            if not rs:
                continue
            cells, texcells, means = [], [], []
            for B in sizes:
                xs = [row_at(r, B)['excess_pct'] for r in rs if row_at(r, B)]
                m, se = ms(xs)
                means.append(m)
                cells.append(fmt_pm(m, se))
                texcells.append(f'${m:+.1f}$' if abs(m) < 1000 else f'${m:+.0f}$')
            # turnaround: bank size of the minimum, and the rise from it to the largest bank
            i = min(range(len(means)), key=means.__getitem__)
            turn = f'min at {sizes[i]:,}; +{means[-1] - means[i]:.1f} after' if i < len(means) - 1 and means[-1] - means[i] > 0.3 else '-'
            md.append(f'| {label} | {len(rs)} | ' + ' | '.join(cells) + f' | {turn} |')
            tex.append(f'  {label} & ' + ' & '.join(texcells) + ' \\\\')
            Bmax = sizes[-1]
            pr = [r['ray_probe']['1000'] for r in rs]
            d = {'label': label, 'n': len(rs),
                 'of3': [ms([of_factor(r, B, 1) for r in rs if row_at(r, B)])[0] for B in sizes],
                 'of2': [ms([of_factor(r, B, 0) for r in rs if row_at(r, B)])[0] for B in sizes],
                 'of3_calm': ms([of_factor(r, Bmax, 1, calm=True) for r in rs])[0],
                 'oracle3': ms([of_oracle(r, 1) for r in rs])[0], 'oracle2': ms([of_oracle(r, 0) for r in rs])[0],
                 'oracle3_calm': ms([of_oracle(r, 1, calm=True) for r in rs])[0],
                 'wmax': ms([row_at(r, Bmax)['wmax_mean'] for r in rs]),
                 'frac_amp': ms([p['frac_pasts_mean_amp_gt1'] for p in pr]),
                 'med_amp': ms([p['log10_mean_amp_median'] for p in pr]),
                 'q90_amp': ms([p['log10_mean_amp_q90'] for p in pr]),
                 'cap_amp': ms([math.log10(max(p['mean_amp_mean_capped'], 1e-300)) for p in pr]),
                 'kappa': ms([r['logit_scale'] for r in rs]),
                 'beta': ms([r['beta'] for r in rs]) if rs[0].get('beta') else None,
                 'beta_uv': [ms([r['beta_uv'][j] for r in rs]) for j in (0, 1)] if rs[0].get('beta_uv') else None}
            diag.append(d)
        g = lambda x: 'nan' if math.isnan(x) else (f'{x:.2f}' if x < 10 else (f'{x:.1f}' if x < 100 else f'{x:,.0f}'))
        o3 = diag[0]['oracle3'] if diag else float('nan')
        md += ['', 'Over-forecast factor of the event {|v| > t_p}, p = 1e-3: forecast probability averaged over the test pasts, '
               f'divided by p, by bank size.  The oracle forecast gives {g(o3)} on the same pasts '
               f"(calmer half of the pasts: {g(diag[0]['oracle3_calm']) if diag else 'nan'}).", '',
               '| model | ' + ' | '.join(f'{B:,}' for B in sizes) + f' | calm pasts, {sizes[-1]:,} |', '|---|' + '---|' * (len(sizes) + 1)]
        tex += [f'%% ---- {data}, {enc}: over-forecast factor p=1e-3 by bank size {sizes}; oracle {g(o3)}']
        for d in diag:
            md.append(f"| {d['label']} | " + ' | '.join(g(x) for x in d['of3']) + f" | {g(d['of3_calm'])} |")
            tex.append(f"  {d['label']} & " + ' & '.join(g(x).replace(',', '{,}') for x in d['of3']) + ' \\\\')
        md += ['', 'Ray probe at scale c = 1000 (tail amplification measured on radially scaled futures): share of pasts whose '
               'direction-averaged amplification exceeds 1; median and 90% quantile over pasts of its log10; '
               'log10 of its mean over pasts (each capped at 1e12).  Then the over-forecast factor for p = 1e-2 at the largest bank, '
               f"(oracle: {g(diag[0]['oracle2']) if diag else 'nan'}), the learned scale and exponents.", '',
               '| model | share amp > 1 | log10 amp median | log10 amp q90 | log10 mean amp | OF p=1e-2 | mean max weight | kappa | b |',
               '|---|---|---|---|---|---|---|---|---|']
        tex += [f'%% ---- {data}, {enc}: ray probe: share amp>1, median log10 amp, q90 log10 amp, log10 mean amp (capped)']
        for d in diag:
            b = '-' if d['beta'] is None else f"{d['beta'][0]:.1f}"
            if d['beta_uv']:
                b += f" (b_u {d['beta_uv'][0][0]:.1f}, b_v {d['beta_uv'][1][0]:.1f})"
            md.append(f"| {d['label']} | {d['frac_amp'][0]:.3f} | {d['med_amp'][0]:.1f} | {d['q90_amp'][0]:.1f} | {d['cap_amp'][0]:.1f} | "
                      f"{g(d['of2'][-1])} | {d['wmax'][0]:.3f} | {d['kappa'][0]:.2f} | {b} |")
            tex.append(f"  {d['label']} & {d['frac_amp'][0]:.2f} & ${d['med_amp'][0]:.1f}$ & ${d['q90_amp'][0]:.1f}$ & ${d['cap_amp'][0]:.1f}$ \\\\")
        md.append('')
        tex.append('')
    (OUT / 'summary.md').write_text('\n'.join(md))
    (OUT / 'tables.tex').write_text('\n'.join(tex))
    print('\n'.join(md))


if __name__ == '__main__':
    main()
