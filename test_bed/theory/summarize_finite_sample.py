"""Tables and a figure for theory/finite_sample_gaussian.py.

Usage (from test_bed/):  python -m theory.summarize_finite_sample
"""
import json
import math
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

from theory.finite_sample_gaussian import FAMILIES, LOSSES

RES = Path('results/theory')
COLORS = {'1way': '#2a78d6', '2way': '#eb6834', 'joint': '#1baf7a'}
MARKERS = {'1way': 'o', '2way': 's', 'joint': 'D'}
LABELS = {'1way': 'one-way', '2way': 'two-way', 'joint': 'joint'}


def mean_se(xs):
    xs = [x for x in xs if x is not None]
    m = sum(xs) / len(xs)
    v = sum((x - m) ** 2 for x in xs) / max(1, len(xs) - 1)
    return m, math.sqrt(v / len(xs)), len(xs)


def n_params(fam, d):
    """Number of forecast parameters (what the v|u forecast depends on)."""
    return {'dot': d * d, 'l2': d * d + d * (d + 1) // 2, 'quad': d * d + d * (d + 1) // 2}[fam]


def load(tag='finite_sample_gaussian'):
    pop, mi, runs = {}, {}, defaultdict(list)
    for path in sorted((RES / tag).glob('*.json')):
        r = json.loads(path.read_text())
        d, rho = r['d'], r['rho']
        mi[f'{d}/{rho}'] = r['mutual_information']
        pop.update({f'{d}/{rho}/{k}': v for k, v in r['population_bias'].items()})
        for x in r['runs']:
            runs[(d, rho, x['n'])].append(x['err'])
    return pop, mi, runs


def main():
    pop, mi, runs = load()
    settings = sorted({(d, rho) for d, rho, _ in runs})
    lines = ['# Linear-Gaussian contrastive forecaster at finite n', '',
             'Generated by `python -m theory.summarize_finite_sample` from '
             '`results/theory/finite_sample_gaussian/*.json`.', '',
             'Each cell: mean forecast error E_u KL(true v|u || fitted v|u) as a fraction of '
             'the mutual information I(u;v) (0 = perfect, 1 = no better than climatology). '
             'Column "inf" is the population optimum of that loss (its bias), as in Table 2 of the note. '
             'n = number of training pairs, full-batch empirical loss.', '']

    for d, rho in settings:
        I = mi[f'{d}/{rho}']
        ns = sorted(n for dd, rr, n in runs if (dd, rr) == (d, rho))
        lines += [f'## d = {d}, rho = {rho}  (I(u;v) = {I:.4f} nats)', '',
                  '| family | loss | ' + ' | '.join(str(n) for n in ns) + ' | inf |',
                  '|---|---|' + '---|' * (len(ns) + 1)]
        for fam in FAMILIES:
            for loss in LOSSES:
                cells = []
                for n in ns:
                    m, se, _ = mean_se([e[f'{fam}/{loss}'] for e in runs[(d, rho, n)]])
                    cells.append(f'{m / I:.3f}')
                bias = pop[f'{d}/{rho}/{fam}/{loss}'] / I
                lines.append(f'| {fam} | {loss} | ' + ' | '.join(cells) + f' | {max(bias, 0):.3f} |')
        # paired comparison joint vs one-way for L2
        lines += ['', 'L2, joint minus one-way (paired, nats; negative = joint better), mean +- 2 se:', '',
                  '| n | ' + ' | '.join(str(n) for n in ns) + ' |', '|---|' + '---|' * len(ns)]
        for other in ['2way', 'joint']:
            cells = []
            for n in ns:
                diffs = [e[f'l2/{other}'] - e['l2/1way'] for e in runs[(d, rho, n)]
                         if e[f'l2/{other}'] is not None and e['l2/1way'] is not None]
                m, se, _ = mean_se(diffs)
                cells.append(f'{m:+.4f} +- {2 * se:.4f}')
            lines.append(f'| {other} - 1way | ' + ' | '.join(cells) + ' |')
        # one-way finite-n error against the k/(2n) rule
        cells = []
        for n in ns:
            m, _, _ = mean_se([e['l2/1way'] for e in runs[(d, rho, n)]])
            cells.append(f'{m / (n_params("l2", d) / (2 * n)):.2f}')
        lines += ['', f'One-way L2 error divided by k/(2n), k = {n_params("l2", d)} forecast parameters '
                  '(1 = the textbook rate for a well-specified maximum-likelihood fit):', '',
                  '| n | ' + ' | '.join(str(n) for n in ns) + ' |', '|---|' + '---|' * len(ns),
                  '| ratio | ' + ' | '.join(cells) + ' |', '']

    (RES / 'finite_sample_gaussian.md').write_text('\n'.join(lines))
    print('\n'.join(lines))
    plot(pop, mi, runs, settings)


def plot(pop, mi, runs, settings):
    panels = [s for s in [(1, 0.1), (1, 0.5), (1, 0.9), (8, 0.5)] if s in settings]
    fig, axes = plt.subplots(1, len(panels), figsize=(3.4 * len(panels), 3.3), sharey=False)
    axes = [axes] if len(panels) == 1 else axes
    for ax, (d, rho) in zip(axes, panels):
        I = mi[f'{d}/{rho}']
        ns = sorted(n for dd, rr, n in runs if (dd, rr) == (d, rho))
        for loss in LOSSES:
            ms, ses = [], []
            for n in ns:
                m, se, _ = mean_se([e[f'l2/{loss}'] for e in runs[(d, rho, n)]])
                ms.append(m / I)
                ses.append(2 * se / I)
            ax.errorbar(ns, ms, yerr=ses, color=COLORS[loss], marker=MARKERS[loss], ms=5,
                        lw=2, capsize=0, label=LABELS[loss])
            bias = pop[f'{d}/{rho}/l2/{loss}'] / I
            if bias > 1e-6:
                ax.axhline(bias, color=COLORS[loss], lw=1, ls='--')
        ax.set_xscale('log', base=2)
        ax.set_yscale('log')
        ax.set_title(f'd = {d}, ρ = {rho}', fontsize=10)
        ax.set_xlabel('training pairs n')
        ax.grid(True, which='major', color='#e6e6e6', lw=0.6)
        for s in ['top', 'right']:
            ax.spines[s].set_visible(False)
    axes[0].set_ylabel('forecast error / I(u;v)')
    axes[0].legend(frameon=False, fontsize=8, title='L² score', title_fontsize=8)
    fig.text(0.5, -0.04, 'Dashed: population bias of the same loss (n = ∞). Bars: ±2 s.e.',
             ha='center', fontsize=8, color='#555555')
    fig.tight_layout()
    fig.savefig(RES / 'finite_sample_gaussian.png', dpi=160, bbox_inches='tight')


if __name__ == '__main__':
    main()
